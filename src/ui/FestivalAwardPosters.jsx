export function posterFor(name = '', id = '') {
  const n = String(name).toLowerCase();
  const hit = Object.entries(POSTERS).find(([slug, p]) => slug === id || p.names.some((x) => x.toLowerCase() === n));
  return hit ? { slug: hit[0], poster: hit[1] } : null;
}

export default function DesignedPoster({ slug, poster, kind, className = '' }) {
  const label = `${kind} artwork: ${poster.t1} ${poster.t2} poster`;
  return (
    <div className={`feature-art fpx fpx-${slug} fpx-${poster.align} ${className}`} role="img" aria-label={label}>
      <span className="fpx-m" aria-hidden="true"><i className="m1" /><i className="m2" /><i className="m3" /></span>
      <span className="fpx-kicker">{poster.kicker}</span>
      <span className="fpx-title"><b>{poster.t1}</b><b>{poster.t2}</b></span>
      <span className="fpx-tag">{poster.tag}</span>
      <span className="fpx-stamp">{poster.stamp}</span>
    </div>
  );
}
